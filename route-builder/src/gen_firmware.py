"""Build the Zumi Route Player sketch: the robot-tested move functions (verbatim from the transpiled
builder output) + an EEPROM route loader/runner + a USB upload receiver.
usage: gen_firmware.py TESTED.ino OUT_DIR/ZumiRoutePlayer.ino"""
import re, sys
SRC, OUT = sys.argv[1], sys.argv[2]
c = open(SRC, encoding='utf-8').read()
globals_line = re.search(r'^int targetHeading,.*?;$', c, re.M).group(0)
# the firmware declares secPerBlock (float) and gapMs itself; drop them (and the old blockTime) from the int list
names = [x.strip() for x in globals_line[len('int '):-len(' = 0;')].split(',')]
names = [x for x in names if x not in ('gapMs', 'blockTime', 'secPerBlock')]
globals_line = 'int ' + ', '.join(names) + ' = 0;'
funcs = c[c.index('void loop() {}') + len('void loop() {}'):].strip()
for f in ['void turn()', 'void straight()', 'void back()', 'void across()', 'void lineTrace()']:
    assert f in funcs, f
# setup() preamble the converter always emits (sensor / motor / gyro init)
pre = re.search(r'void setup\(\) \{\n(.*?Zumi\.GyroCalibration\(\);)', c, re.S).group(1)

FW = r'''// Zumi Route Player v4 - generated by gen_firmware.py. Do not edit by hand.
// Boot: listen 1.5 s on USB for a route upload (saved to EEPROM, robot does not drive),
// otherwise load the saved route and run it.
// Move functions below are copied unchanged from a robot-tested Rokitbrick project.
#include "Zumi.h"
#include <avr/eeprom.h>

%(globals)s

float secPerBlock = 1;   // seconds per grid block (decimal), sent as ms
int gapMs = 500;          // 5AR / 5AL gap, ms

#define FW_VERSION 4
#define IMG_MAX 900
#define N_SETTINGS 13
// EEPROM image: 'Z' 'R' version nSettings, nSettings x int16 LE, nSteps, nSteps x (op, uint16 LE), CRC-8 (poly 0x07)
enum { OP_ACROSS = 1, OP_FWD = 2, OP_BACK = 3, OP_TURN = 4, OP_WAIT = 5, OP_LINE = 6, OP_GAP = 7, OP_MOVE = 8 };

static uint8_t ee(uint16_t a) { return eeprom_read_byte((const uint8_t *)a); }
static uint16_t ee16(uint16_t a) { return (uint16_t)ee(a) | ((uint16_t)ee(a + 1) << 8); }

static void motorsStop() {
  Zumi.DCMotor(M1, STOP, 0);
  Zumi.DCMotor(M2, STOP, 0);
}

static int readByteTimeout(uint16_t ms) {
  unsigned long t = millis();
  while (!Serial.available()) { if (millis() - t > ms) return -1; }
  return Serial.read();
}

// returns image length if the saved image is valid, else 0
static uint16_t imageValid() {
  if (ee(0) != 'Z' || ee(1) != 'R' || ee(2) != FW_VERSION || ee(3) != N_SETTINGS) return 0;
  uint16_t nStepsAt = 4 + 2 * N_SETTINGS;
  uint16_t len = nStepsAt + 1 + 3 * (uint16_t)ee(nStepsAt);
  if (len + 1 > IMG_MAX) return 0;
  uint8_t crc = 0;                                  // CRC-8, polynomial 0x07
  for (uint16_t i = 0; i < len; i++) {
    crc ^= ee(i);
    for (uint8_t k = 0; k < 8; k++) crc = (crc & 0x80) ? (uint8_t)((crc << 1) ^ 0x07) : (uint8_t)(crc << 1);
  }
  return crc == ee(len) ? len + 1 : 0;
}

// host sends: 'Z' 'U' lenLo lenHi, then waits for 'A', then 16-byte chunks, each answered with '.'
static void receiveUpload() {
  int lo = readByteTimeout(300), hi = readByteTimeout(300);
  if (lo < 0 || hi < 0) { Serial.println(F("ERR header")); return; }
  uint16_t len = (uint16_t)lo | ((uint16_t)hi << 8);
  if (len < 6 || len > IMG_MAX) { Serial.println(F("ERR length")); return; }
  eeprom_update_byte((uint8_t *)0, 0);          // invalidate the old route until the new one is complete
  Serial.write('A');
  uint8_t first0 = 0, first1 = 0;
  for (uint16_t i = 0; i < len; i++) {
    int b = readByteTimeout(1000);
    if (b < 0) { Serial.println(F("ERR timeout")); return; }
    if (i == 0) first0 = b; else if (i == 1) first1 = b;
    else eeprom_update_byte((uint8_t *)i, (uint8_t)b);
    if ((i & 15) == 15 || i == len - 1) Serial.write('.');
  }
  eeprom_update_byte((uint8_t *)1, first1);      // magic last, so a broken upload never looks valid
  eeprom_update_byte((uint8_t *)0, first0);
  uint16_t ok = imageValid();
  if (ok == len) { Serial.print(F("OK ")); Serial.println(len); }
  else { eeprom_update_byte((uint8_t *)0, 0); Serial.println(F("ERR checksum")); }
}

static void halt() { motorsStop(); while (1) {} }

void setup() {
  Serial.begin(115200);
  Zumi.MotorInit();
  motorsStop();
  Serial.println(F("ZRP4 READY"));
  unsigned long t0 = millis();
  while (millis() - t0 < 1500) {
    if (Serial.available()) {
      int b = Serial.read();
      if (b == 'Z' && readByteTimeout(300) == 'U') { receiveUpload(); Serial.println(F("SAVED - unplug, then switch on to run")); halt(); }
      if (b == '?') { Serial.print(F("ZRP4 ROUTE ")); Serial.println(imageValid()); }
    }
  }
  if (!imageValid()) { Serial.println(F("NO ROUTE")); halt(); }

%(pre)s

  // settings, in the order the route builder writes them
  int16_t s[N_SETTINGS];
  for (uint8_t i = 0; i < N_SETTINGS; i++) s[i] = (int16_t)ee16(4 + 2 * i);
  straightSpeed = s[0]; secPerBlock = s[1] / 1000.0; acrossSpeed = s[2]; steerStrength = s[3];
  traceCs = s[4]; BL = s[5]; BR = s[6]; spdStraight = s[7]; spdFast = s[8]; spdSlow = s[9];
  spdPivot = s[10]; lostSpd = s[11]; gapMs = s[12];

  Zumi.delayForGyro(0.5);
  targetHeading = round(Zumi.eulerAngle(YAW));

  uint16_t at = 4 + 2 * N_SETTINGS;
  uint8_t n = ee(at++);
  for (uint8_t k = 0; k < n; k++, at += 3) {
    uint8_t op = ee(at);
    uint16_t v = ee16(at + 1);
    switch (op) {
      case OP_ACROSS: acrossBlocks = (int)v; across(); break;
      // v = half blocks; same as the blocks' "straightTime = (n * (secPerBlock * 100))" (1/100 s, truncated)
      case OP_FWD: straightTime = (int)((v * 0.5) * (secPerBlock * 100)); straight(); break;
      case OP_BACK: straightTime = (int)((v * 0.5) * (secPerBlock * 100)); back(); break;
      case OP_GAP: straightTime = (v == 65535 ? gapMs : (int)v) / 10; straight(); break;  // ms, 65535 = gapMs
      case OP_MOVE: Zumi.DCMove(FORWARD, straightSpeed); Zumi.delayForGyro(v * 0.01); break;  // plain move, keeps rolling
      case OP_TURN: targetHeading += (int16_t)v; turn(); break;                          // signed degrees
      case OP_WAIT: Zumi.delayForGyro(v * 0.01); break;                                  // 1/100 s
      case OP_LINE: if (v) traceCs = (int)v; lineTrace(); break;                         // 0 = keep traceCs
    }
  }
  motorsStop();
}

void loop() {}

// ---------------- move functions (unchanged from the tested project) ----------------
%(funcs)s
'''
out = FW % {'globals': globals_line, 'pre': pre, 'funcs': funcs}
open(OUT, 'w', encoding='utf-8', newline='\n').write(out)
print('wrote', OUT, len(out))
